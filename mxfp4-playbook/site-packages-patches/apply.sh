#!/usr/bin/env bash
# apply.sh — apply the R19j site-packages patches to a venv.
#
# Usage: ./apply.sh [SITE_PACKAGES_DIR]
#   SITE_PACKAGES_DIR defaults to the running python's first site-packages dir.
#
# Prereq: that site-packages contains PRISTINE amd-quark==0.12.post1 and
# transformers==5.2.0 (py3.12). If files are already patched, `patch` will
# detect "Reversed (or previously applied) patch" — use -N to skip those.
set -uo pipefail

DIR="$(cd "$(dirname "$0")" && pwd)"
SP="${1:-$(python3 -c 'import site;print(site.getsitepackages()[0])' 2>/dev/null || python3 -c 'import site;print(site.getsitepackages()[0])')}"
[ -d "$SP" ] || { echo "site-packages not found: $SP" >&2; exit 1; }
echo "target site-packages: $SP"

declare -A TARGET=(
  [01-quark-awq.py.patch]="quark/torch/algorithm/awq/awq.py"
  [02-quark-evaluation.py.patch]="quark/contrib/llm_eval/evaluation.py"
  [03-quark-quantization-api.py.patch]="quark/torch/quantization/api.py"
  [04-quark-post-calibration.py.patch]="quark/torch/quantization/post_calibration.py"
  [05-quark-hw-emulation-interface.py.patch]="quark/torch/kernel/hw_emulation/hw_emulation_interface.py"
  [06-quark-model-preparation.py.patch]="quark/torch/utils/llm/model_preparation.py"
  [07-quark-gpu-stream.h.patch]="quark/torch/include/gpu_stream.h"
  [08-transformers-modeling-qwen3_5.py.patch]="transformers/models/qwen3_5/modeling_qwen3_5.py"
)

rc=0
for p in 01-quark-awq.py.patch 02-quark-evaluation.py.patch 03-quark-quantization-api.py.patch \
         04-quark-post-calibration.py.patch 05-quark-hw-emulation-interface.py.patch \
         06-quark-model-preparation.py.patch 07-quark-gpu-stream.h.patch \
         08-transformers-modeling-qwen3_5.py.patch; do
  f="$SP/${TARGET[$p]}"
  if [ ! -f "$f" ]; then
    echo "SKIP (missing target): $p -> ${TARGET[$p]}"
    rc=1
    continue
  fi
  cp "$f" "$f.bak_r19j_apply" 2>/dev/null
  if patch -s -N "$f" < "$DIR/$p"; then
    echo "APPLIED: $p"
  else
    # -N makes patch exit 1 on "previously applied" — check whether it actually is
    if patch -s -R --dry-run "$f" < "$DIR/$p" >/dev/null 2>&1; then
      echo "ALREADY APPLIED (skipped): $p"
    else
      echo "FAILED: $p (backup at $f.bak_r19j_apply)"
      rc=1
    fi
  fi
done

echo
echo "=== post-apply audit (expect exactly the 8 patched files listed) ==="
python3 "$DIR/audit_site_packages.py" "$SP" || true
exit $rc
