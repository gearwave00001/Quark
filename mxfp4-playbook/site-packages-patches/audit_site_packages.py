#!/usr/bin/env python3
"""audit_site_packages.py — list installed files that deviate from their pristine wheels.

Hashes every file recorded in each distribution's RECORD against the actual file
on disk (urlsafe-base64 sha256, as pip writes it). Prints only distributions with
deviations. On a pristine venv: prints nothing. On the R19j-patched venv: prints
exactly the 8 files in this folder's README.

Usage:
  python3 audit_site_packages.py                 # current interpreter's site-packages
  python3 audit_site_packages.py /path/to/sp     # explicit site-packages dir
"""
import base64
import hashlib
import importlib.metadata
import os
import sys


def rec_digest(data: bytes) -> str:
    return base64.urlsafe_b64encode(hashlib.sha256(data).digest()).rstrip(b"=").decode()


def main() -> None:
    if len(sys.argv) > 1:
        sp = os.path.abspath(sys.argv[1])
    else:
        import site
        sp = site.getsitepackages()[0]
    sp_prefix = os.path.realpath(sp) + os.sep

    dists = [
        d for d in importlib.metadata.distributions()
        if d._path and os.path.realpath(str(d._path)).startswith(sp_prefix)
    ]
    dists.sort(key=lambda d: ((d.metadata.get("Name") or "?"), str(d._path)))
    total_modified = 0
    for md in dists:
        try:
            rec = md.read_text("RECORD") or ""
        except Exception:
            continue
        if not rec.strip():
            continue
        changed = []
        for line in rec.splitlines():
            parts = line.split(",")
            if len(parts) < 2:
                continue
            p, digest = parts[0], parts[1]
            if not p or p.endswith("RECORD") or ".dist-info" in p:
                continue
            if not digest.startswith("sha256="):
                continue
            full = os.path.normpath(os.path.join(sp, p))
            if not os.path.exists(full):
                continue
            if digest == f"sha256={rec_digest(open(full, 'rb').read())}":
                continue
            changed.append(p)
        if changed:
            total_modified += len(changed)
            print(f"{md.metadata.get('Name')}=={md.version}: {len(changed)} modified")
            for c in sorted(changed):
                print(f"   M {c}")
    if total_modified == 0:
        print(f"(all files match their wheel RECORDs under {sp})")


if __name__ == "__main__":
    main()
